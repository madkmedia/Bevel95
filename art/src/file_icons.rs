//! The old Windows' pictures for kinds of file (used by `core::file_kinds`): every picture the
//! Reference PCs' own tables of kinds name (the shell's text, settings, program, batch, system-file
//! and font pictures, and the pictures of Help, WordPad, Paint, Internet Explorer, Media Player,
//! Imaging and the rest), 32Ã—32 and 16Ã—16, each look its own. They are the icons in the PCs' own
//! files (`private/probes/file-icons/survey.md`, brief 81), drawn as each Windows drew them, by
//! `private/probes/file-icons/cut.ps1`: Windows 95's 16-color images put to the nearest of
//! Windows' 16 colors (on every screen); Windows 98's in True Color from the 256-color image
//! where there is one, every channel cut to 5 bits with its lowest kept bit repeated below, else
//! the 16-color image as stored; Windows 2000's in True Color from the 256-color image where
//! there is one, else the 16-color one, through 5 bits per channel the usual way; 98's and
//! 2000's at 256 and 16 colors their 16-color images put to the 16 colors. Where a file had no
//! 16Ã—16 (or, once, no 32Ã—32) image, the other size halved (every other pixel) or doubled (not
//! measured: no such kind was on the PCs' screens).
//!
//! A sheet holds the pictures one after the other: the number of colors n (a byte), n colors (red,
//! green, blue), then the pixels, 0 see-through and k the k-th color, two to a byte (the high half
//! first) when n is 15 or less, else one to a byte. The tables say where each begins and how big
