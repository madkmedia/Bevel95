//! The Start menu's pictures, pixel for pixel: its own entries (32×32), the folder of the Programs
//! menus, the entries of Settings and Find and the Documents menu (16×16), the Remove Shortcuts
//! tree's, and the few other pictures `core::icons` holds (the message box warning, 2000's speaker,
//! the Run, Shut Down and Log Off windows' pictures), for Windows 95, 98 and 2000.
//!
//! Cut from the owner's own Windows 95, 98 and 2000 (the Reference PCs, docs/decisions.md). The
//! Start menu's 32×32 entries, the program groups, the dialogs' pictures and the 16×16 entries of
//! the Start menu with small icons were first taken from GUIdebook's screenshots and the v86
//! emulator; since 2026-11-18 each is cut from the Reference PCs' True Color captures or read
//! from their Windows' own files and found identical, pixel for pixel (docs/decisions.md, "Every
//! picture from the owner's own Windows"; `private/probes/own-sources`). The 32×32 entries: 95's
//! from `vm/win95-truecolor-documents-0.png`, 98's from `vm/win98-truecolor-accessories.png`,
//! 2000's from `vm/win2000-truecolor-documents-0.png`. The last ten were found on 2026-11-18 in
//! new captures of the PCs (`vm/own-pictures/`: 98 with user profiles on, so that it shows Log
//! Off; 2000 with Display Favorites and Display Logoff; 95 and 2000 with small icons): 98's and
//! 2000's 32×32 Log Off and 2000's seven small entries were identical; 95's small Documents
//! (1 pixel) and Find (icon 23's image, one pixel further right than icon 134's) were replaced.
//! New then, each look's own where it had shown another's: 98's Windows Update (it showed
//! 2000's), 2000's Favorites, small Favorites and small Log Off (they showed 98's).
//! Which pixels are see-through: where a capture shows an item highlighted and not, the pixels
//! that change with the highlight; a file's picture says it itself. The Settings and Find icons
//! come from the Reference PCs (True Color), each entry captured selected and not
//! (`tools/dev/cutmenu.ps1`).

